#!/usr/bin/env node
/**
 * Refresh typed MVSep model descriptors from the public algorithm endpoint.
 * No credentials and no paid operations.
 * Usage: bun run models:update [--file <cached-json>]
 */
import fs from 'node:fs/promises';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const source = process.argv[2] === '--file'
  ? JSON.parse(await fs.readFile(process.argv[3], 'utf8'))
  : await (async () => {
      const response = await fetch('https://mvsep.com/api/app/algorithms', { signal: AbortSignal.timeout(25000) });
      if (!response.ok) throw new Error('Cannot fetch MVSep algorithms: HTTP ' + response.status);
      return response.json();
    })();
const algorithms = Array.isArray(source) ? source : source?.data;
if (!Array.isArray(algorithms) || algorithms.length < 3) throw new Error('Unexpected algorithm response');
const parse = value => {
  if (!value) return null;
  if (typeof value !== 'string') return value;
  try { return JSON.parse(value); } catch { throw new Error('Invalid JSON metadata value'); }
};
const propertyName = name => {
  const descriptiveName = /^Ensemble\s*\(/i.test(name) ? name.replace(/[(),]/g, ' ') : name;
  const words = descriptiveName.replace(/\(.*$/, '').replace(/^MVSep\s+/i, 'MVSep_')
    .replace(/[^a-z0-9]+/gi, ' ').trim().split(/\s+/);
  return words.map((p,i) => i===0 ? p.replace(/^([0-9])/, '_$1') : p[0]?.toUpperCase()+p.slice(1)).join('') || 'Model';
};
const byId = new Set();
const byName = new Set();
const records = [];
for (const entry of algorithms) {
  const id = entry.render_id;
  if (!Number.isSafeInteger(id) || id < 0 || byId.has(id)) throw new Error('Invalid or duplicate algorithm ID '+id);
  byId.add(id);
  const name = id === 20 ? 'Demucs4_HT' : id === 37 ? 'DrumSep' : id === 88 ? 'MVSep_Synth' : propertyName(entry.name);
  let unique = name;
  if (byName.has(unique)) unique += '_' + id;
  if (byName.has(unique)) throw new Error('Model name collision for ID '+id);
  byName.add(unique);
  const published = parse(entry.outputs);
  const variants = parse(entry.output_variants);
  const fields = (entry.algorithm_fields ?? []).filter(f => f && typeof f.name === 'string').map(f => ({
    name: f.name,
    ...(f.text ? { text: f.text } : {}),
    ...(f.server_key ? { serverKey: f.server_key } : {}),
    ...(f.default_key !== undefined && f.default_key !== null ? { defaultKey: String(f.default_key) } : {}),
    ...(parse(f.options) ? { choices: parse(f.options) } : {}),
  }));
  const profiles = Array.isArray(variants?.variants) ? variants.variants.map(v => ({
    match: v.match ?? {},
    stems: Object.keys(v.outputs ?? {}),
  })).filter(v => v.stems.length > 0) : [];
  // output_stems is sometimes a human-readable description, not a file name.
  const outputs = published && !Array.isArray(published) && typeof published === 'object'
    ? Object.keys(published) : [];
  const declared = Array.isArray(parse(entry.output_stems)) ? parse(entry.output_stems) : [];
  const stems = [...new Set([...outputs, ...profiles.flatMap(p => p.stems), ...(outputs.length ? [] : declared)])]
    .filter(s => typeof s === 'string' && s.length > 0);
  if (id === 37) stems.push(...['hihat', 'crash_ride'].filter(s => !stems.includes(s))); // historic aliases, not guarantees
  records.push({ key: unique, id, name: entry.name, active: Boolean(entry.is_active),
    group: entry.algorithm_group?.name ?? 'Other', groupId: entry.algorithm_group_id ?? -1,
    widget: entry.audio_widget ?? 'single_upload', stems,
    ...(Number.isFinite(Number(entry.price_coefficient)) && Number(entry.price_coefficient)>0 ? {priceCoefficient: Number(entry.price_coefficient)} : {}),
    ...(Number.isFinite(Number(entry.rating?.average)) && Number(entry.rating?.total)>0 ? {rating: {average:Number(entry.rating.average), total:Number(entry.rating.total)}} : {}),
    ...(fields.length ? { fields } : {}),
    ...(profiles.length ? { profiles } : {}),
  });
}
const header = '// AUTO-GENERATED by scripts/update-models.mjs from https://mvsep.com/api/app/algorithms\n'
 + '// Snapshot of public MVSep models. Refresh explicitly with bun run models:update.\n'
 + '// Stems are metadata hints, not promises; the runner verifies real output names.\n';
const data = records.map(({key,...record}) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(record) + ',').join('\n');
const output = header + '\nexport const generatedModels = {\n' + data + '\n} as const;\n';
await fs.writeFile(path.join(repoRoot, 'src/models.generated.ts'), output);
const summary = {total: records.length, active: records.filter(m => m.active).length,
  withOutputs: records.filter(m => m.stems.length > 0).length,
  withOptionProfiles: records.filter(m => m.profiles?.length).length,
  names: records.map(m => m.key)};
await fs.writeFile(path.join(repoRoot,'src/models-catalog-summary.json'), JSON.stringify(summary,null,2)+'\n');

const modelRows = records.map(model => {
  const names = model.stems.length ? model.stems.map(x => '\`' + x + '\`').join(', ') : '_Not published_';
  return '| \`Models.' + model.key + '\` | ' + model.id + ' | ' +
    model.name.replaceAll('|', '\\|') + ' | ' + names + ' | ' +
    (model.profiles?.length ?? 0) + ' | ' + (model.active ? 'Yes' : 'No') + ' |';
});
const markdown = [
  '---', 'title: Supported models and output stems',
  'description: Generated catalog of MVSep algorithms, stem names, and option-dependent output variants.',
  '---', '',
  '# MVSep model catalog', '',
  'This catalog is generated from the public MVSep API with \`bun run models:update\`.',
  'Every row is also available as a typed descriptor for \`separate(Models.<name>, options)\`.',
  'The playground ships with this snapshot and can refresh the live list.', '',
  '**Important:** Published outputs are *hints*, not guarantees. Some depend on model options.',
  'Option-dependent observed profiles are included in the generated descriptors and used by the visual graph.',
  'The runner checks the *actual filenames* before feeding downstream steps.',
  'Models without published output names have no guessed stem ports.', '',
  '**Snapshot:** ' + records.length + ' algorithms; ' + records.filter(x=>x.active).length +
    ' active; ' + records.filter(x=>x.stems.length).length + ' have named outputs; ' +
    records.filter(x=>x.profiles?.length).length + ' have option-dependent output profiles.', '',
  '| SDK model | ID | Display name | Published output names (union of observed variants) | Output variants | Active |',
  '| --- | ---: | --- | --- | ---: | --- |', ...modelRows, '',
  'Refresh with \`bun run models:update\`. Then run \`bun run test\` and \`cd docs && bun run build\`.',
  'For newer models not yet in the snapshot, use \`modelFromAlgorithm(await client.getAlgorithm(id))\`.', '',
].join('\n');
await fs.writeFile(path.join(repoRoot,'docs/src/content/docs/reference/models.md'), markdown);

console.log(JSON.stringify({ total: summary.total, active: summary.active,
  withOutputs: summary.withOutputs, withOptionProfiles: summary.withOptionProfiles }, null,2));
